// Lightweight i18n: Chinese source strings ARE the keys. Lookup order:
// target language → English → the Chinese key itself, so untranslated
// strings degrade gracefully. Default = system language; localStorage wins.
import { ref } from 'vue'

export const LANGS: [string, string][] = [
  ['zh', '简体中文'],
  ['zh-TW', '繁體中文'],
  ['en', 'English'],
  ['ja', '日本語'],
  ['ko', '한국어'],
  ['de', 'Deutsch'],
  ['fr', 'Français'],
  ['es', 'Español'],
  ['ru', 'Русский'],
  ['pt', 'Português'],
]

function detect(): string {
  const l = ((typeof navigator !== 'undefined' && navigator.language) || 'en').toLowerCase()
  if (l.startsWith('zh')) return (l.includes('tw') || l.includes('hk') || l.includes('hant')) ? 'zh-TW' : 'zh'
  for (const [code] of LANGS) if (code !== 'zh' && code !== 'zh-TW' && l.startsWith(code)) return code
  return 'en'
}

const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('bs_lang') : null
export const lang = ref<string>(saved && LANGS.some(([c]) => c === saved) ? saved : detect())

export function setLang(l: string) {
  lang.value = l
  localStorage.setItem('bs_lang', l)
}

